"""Build the Jak 1 Korean font: texture sheets, GOAL table data and a charmap.

Usage:
  python3 build_font.py
      --set menu <menu text file> <font> --set subtitle <subtitle text file> <font>
      --out-tex <custom_assets/jak1/texture_overlays/gamefontnew>
      --out-goal <goal_src/jak1/pc/kr-font-data.gc> --out-charmap-dir <game/assets/fonts>

The sheets hold only the Korean glyphs. The patched decompiler draws them over the
original sheet from the user's ISO, upscaled by layout.SCALE (TextureDB overlay), so
the output has no game data and can be redistributed.
"""
import argparse
import json
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

import layout as L

SHEETS = ("24lo", "24hi", "12lo", "12hi")
PS2_ALPHA_MAX = 128
# glyph box inside a full-res cell; Hangul is drawn a bit taller than wide to
# match the original sheet's tall capitals.
GLYPH_W, GLYPH_H = 44, 54
FONT_INDEX_KR = 1  # "Noto Sans CJK KR" inside NotoSansCJK-*.ttc


def is_hangul_syllable(ch):
    return 0xAC00 <= ord(ch) <= 0xD7A3


@dataclass
class Plan:
    codes: dict = field(default_factory=dict)        # (typeface, syllable) -> (lead, trail)
    entry_cells: dict = field(default_factory=dict)  # table index -> (col, row)
    lo: dict = field(default_factory=dict)           # (col, row) -> (typeface, syllable)
    hi: dict = field(default_factory=dict)


def plan(sets):
    """sets: {typeface key: iterable of syllables}. Each typeface gets its own codes."""
    glyphs = []
    for key in sorted(sets):
        chars = sorted(set(sets[key]))
        bad = [c for c in chars if not is_hangul_syllable(c)]
        if bad:
            raise ValueError(f"not Hangul syllables in {key}: {bad!r}")
        glyphs += [(key, c) for c in chars]
    codes, entry_cells = L.assign(len(glyphs))
    p = Plan(entry_cells=entry_cells)
    for glyph, (lead, trail) in zip(glyphs, codes):
        p.codes[glyph] = (lead, trail)
        cell = entry_cells[L.table_index(lead, trail)]
        (p.hi if trail & 0x80 else p.lo)[cell] = glyph
    return p


def load_font(path, full_res):
    size = 46 if full_res else 23
    index = FONT_INDEX_KR if str(path).lower().endswith(".ttc") else 0
    return ImageFont.truetype(path, size, index=index)


def render_glyph(ch, font, full_res):
    """White glyph with PS2 alpha, sized to the glyph box."""
    w, h = (GLYPH_W, GLYPH_H) if full_res else (GLYPH_W // 2, GLYPH_H // 2)
    size = font.size
    cov = Image.new("L", (size * 2, size * 2), 0)
    ImageDraw.Draw(cov).text((size // 2, size // 2), ch, font=font, fill=255)
    bbox = cov.getbbox() or (0, 0, 1, 1)
    cov = cov.crop(bbox).resize((w, h), Image.LANCZOS)
    alpha = cov.point(lambda a: a * PS2_ALPHA_MAX // 255)
    glyph = Image.new("RGBA", (w, h), (255, 255, 255, 0))
    glyph.putalpha(alpha)
    return glyph


def overlay_sheet(full_res, glyphs, fonts):
    div = 1 if full_res else 2
    cw, ch = L.CELL_W // div, L.CELL_H // div
    sheet = Image.new("RGBA", (L.CANVAS_W // div, L.CANVAS_H // div), (255, 255, 255, 0))
    for (col, row), (key, syl) in glyphs.items():
        g = render_glyph(syl, fonts[key], full_res)
        x = col * cw + (cw - g.width) // 2
        y = row * ch + (ch - g.height) // 2
        sheet.alpha_composite(g, (x, y))
    return sheet


def goal_data(p):
    idx = sorted(p.entry_cells)
    uvs = []
    for i in idx:
        uvs.extend(L.cell_uv(*p.entry_cells[i]))
    return "\n".join([
        ";; GENERATED by tools/kr_font/build_font.py - DO NOT EDIT",
        f";; {len(p.codes)} glyphs, {len(idx)} table entries",
        f"(define *kr-font-table-length* {L.table_length()})",
        f"(define *kr-font-uv-scale-x* {L.UV_SCALE_X})",
        f"(define *kr-font-uv-scale-y* {L.UV_SCALE_Y})",
        "(define *kr-font-entry-index* (new 'static 'boxed-array :type int32 "
        + " ".join(str(i) for i in idx) + " ))",
        "(define *kr-font-entry-uv* (new 'static 'boxed-array :type float "
        + " ".join(f"{v:.8f}" for v in uvs) + " ))",
        "",
    ])


def charmap_json(p, key):
    return json.dumps({c: [lead, trail] for (k, c), (lead, trail) in p.codes.items() if k == key},
                      ensure_ascii=False, indent=1, sort_keys=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", action="append", nargs=3, metavar=("KEY", "TEXT", "FONT"), required=True,
                    help="typeface set: key (menu|subtitle), file with its Korean text, font file")
    ap.add_argument("--out-tex", required=True, type=Path)
    ap.add_argument("--out-goal", required=True, type=Path)
    ap.add_argument("--out-charmap-dir", required=True, type=Path,
                    help="writes jak1_korean_charmap_<key>.json per set")
    a = ap.parse_args()

    sets, font_paths = {}, {}
    for key, text, font in a.set:
        sets[key] = [c for c in Path(text).read_text(encoding="utf-8") if is_hangul_syllable(c)]
        font_paths[key] = font
    p = plan(sets)
    a.out_tex.mkdir(parents=True, exist_ok=True)
    for name in SHEETS:
        full = name.startswith("24")
        fonts = {k: load_font(f, full) for k, f in font_paths.items()}
        sheet = overlay_sheet(full, p.hi if name.endswith("hi") else p.lo, fonts)
        sheet.save(a.out_tex / f"ascii.{name}.png")
    a.out_goal.write_text(goal_data(p), encoding="utf-8")
    for key in sets:
        (a.out_charmap_dir / f"jak1_korean_charmap_{key}.json").write_text(charmap_json(p, key), encoding="utf-8")
    print(", ".join(f"{k}: {len(set(v))}" for k, v in sets.items()), f"-> {len(p.entry_cells)} entries")


if __name__ == "__main__":
    main()
